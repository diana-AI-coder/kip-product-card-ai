"""Промпты для генерации карточки товара."""

from __future__ import annotations

import json

from .schemas import ProductInput

SYSTEM_PROMPT = """Ты — редактор технических карточек товаров для B2B-каталога контрольно-измерительных приборов (КИП). Ты готовишь черновик для контент-менеджера, который будет проверять и публиковать текст.

ЖЁСТКИЕ ПРАВИЛА (нарушение любого пункта делает результат непригодным):
1. Единственный источник фактов — блок INPUT. Не используй общие знания о модели, производителе или типе прибора.
2. Запрещено добавлять характеристики, которых нет в INPUT: материалы, степень защиты, сертификаты, гарантию, страну производства, комплектацию, сроки поставки, цену, преимущества без основания.
3. Не конвертируй и не пересчитывай единицы измерения. Переноси значения в той же записи, что во входных данных (например, «0–1,6 МПа» остаётся «0–1,6 МПа», а не «16 бар»).
4. Если сведений о характеристике нет — не упоминай её и не придумывай замену. Отсутствующие разделы перечисляются отдельно и в текст не попадают.
5. Маркетинговые формулировки допустимы только как пересказ фактов из INPUT. Любое утверждение о свойствах прибора должно опираться на конкретный пункт specs или на description. Оценочные обещания («гарантирует надёжную работу», «долговечен», «безотказен») запрещены, если этих слов нет в INPUT.
6. Не расшифровывай коды и стандарты (IP65, Ex ia IIC T6, G1/2, M20×1,5): переноси обозначение как есть, без пояснений про пыль, влагу или взрывобезопасность.
7. Тон — деловой, нейтральный, без восклицаний, без оценочных превосходных степеней («лучший», «уникальный», «самый точный»).

ТРЕБОВАНИЯ К ПОЛЯМ:
- seo_title: до 70 символов с пробелами, без кавычек и без нагромождения ключевых слов. Обычно: тип прибора + модель + ключевая характеристика + производитель.
- seo_description: от 800 до 1200 символов с пробелами включительно. Сплошной текст без markdown, списков, заголовков и переносов строк. Раскрывает назначение, ключевые характеристики и область применения строго по INPUT.
- key_specs: только характеристики из INPUT specs, каждая отдельным пунктом. source_key — точное имя ключа из INPUT specs (символ в символ). Значение — как во входных данных, без пересчёта.
- search_queries: от 3 до 5 реалистичных поисковых запросов на русском языке, под которые логично оптимизировать страницу. Комбинируй категорию, модель, бренд и характеристику. Не выдумывай частотность.
- commercial_block.text: 2–4 предложения для менеджера — кому подходит прибор и какие задачи решает. Каждое утверждение должно следовать из INPUT.
- commercial_block.basis: массив ТОЧНЫХ имён ключей из INPUT specs (например, «диапазон измерений») либо «description». Слово «specs» или «input» вместо ключей использовать нельзя.

ФОРМАТ ОТВЕТА: только JSON-объект по заданной схеме. Без markdown, без комментариев, без текста до и после JSON."""


def _input_json(product: ProductInput) -> str:
    data = {
        "name": product.name,
        "manufacturer": product.manufacturer,
        "specs": product.specs,
        "description": product.description,
    }
    if product.sku:
        data["sku"] = product.sku
    return json.dumps(data, ensure_ascii=False, indent=2)


def build_user_prompt(product: ProductInput, missing_fields: list[str]) -> str:
    """Собирает пользовательский промпт для первичной генерации."""
    parts = [
        "Сформируй черновик карточки товара по данным ниже.",
        "",
        "INPUT:",
        _input_json(product),
    ]
    if missing_fields:
        parts += [
            "",
            "Во входных данных отсутствуют сведения по разделам: "
            + ", ".join(missing_fields)
            + ". Не выдумывай их — просто не упоминай.",
        ]
    parts += [
        "",
        "Напомню: единицы измерения не конвертируй, характеристики не додумывай.",
    ]
    return "\n".join(parts)


def build_repair_prompt(
    product: ProductInput,
    previous: dict,
    errors: list[str],
    warnings: list[str],
) -> str:
    """Промпт для исправления ответа, не прошедшего проверку."""
    violations = [f"- {item}" for item in errors + warnings]
    return "\n".join(
        [
            "Предыдущий ответ не прошёл проверку. Исправь ТОЛЬКО перечисленные нарушения.",
            "Не добавляй новых фактов и не меняй корректные части без необходимости.",
            "",
            "НАРУШЕНИЯ:",
            *violations,
            "",
            "ОРИЕНТИРЫ:",
            (
                "- seo_title — не более 70 символов с пробелами; сократи формулировку, "
                "сохранив модель и назначение прибора."
            ),
            (
                "- seo_description — строго 800–1200 символов; если текст короче, "
                "дополни его фактами из INPUT, не добавляя новых."
            ),
            (
                "- commercial_block.basis — только точные ключи из INPUT specs "
                "или слово «description»; «specs» вместо ключей не подходит."
            ),
            "",
            "ПРЕДЫДУЩИЙ ОТВЕТ:",
            json.dumps(previous, ensure_ascii=False, indent=2),
            "",
            "INPUT (единственный источник фактов):",
            _input_json(product),
            "",
            "Верни полный JSON по той же схеме.",
        ]
    )
